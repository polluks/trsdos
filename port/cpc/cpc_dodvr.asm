;****************************************************************
;* Amstrad CPC Video Driver for LSDOS 6.3.1L Port		*
;****************************************************************
;* Uses 40x25 character buffer in system RAM. Characters are	*
;* rendered to CPC mode 1 bitmap screen at $C000 from an		*
;* internal 8x8 font.						*
;****************************************************************
	SUBTTL	'<CPC CRTC Video Driver>'
	PAGE

;==============================================================================
; Driver Header
;==============================================================================
DODVR	JR	DOBGN
	DW	DOEND
	DB	3,'$DO'
	DW	DODCB$
	DW	0

DODATA	EQU	$
DO_MASK	DB	0
CURSOR	DW	0		;H=row, L=col
CRSAVE	DB	20H
CRSCHAR	DB	'_'
INVIDEO	DB	0
CURSTATE DB	0

TEXTBUF	DS	1000		;40x25 character buffer

;==============================================================================
; Font expansion table: 4-bit nibble -> mode 1 8-bit color
; Each input bit becomes %01 in output (foreground color)
; Input:   %abcd  Output: %01a01b01c01d
;==============================================================================
FONT_EXP
	DB	%00000000,%00000001,%00000100,%00000101
	DB	%00010000,%00010001,%00010100,%00010101
	DB	%01000000,%01000001,%01000100,%01000101
	DB	%01010000,%01010001,%01010100,%01010101

;==============================================================================
; DO_PUT_CHAR - Write character A at position (H,L)
; Updates text buffer and renders to bitmap screen
;==============================================================================
DO_PUT_CHAR
	PUSH	BC
	PUSH	DE
	PUSH	HL
	PUSH	AF

	; Update text buffer at TEXTBUF[row*40+col]
	LD	D,H		;D=row
	LD	E,L		;E=col
	LD	HL,TEXTBUF
	LD	A,D
	OR	A
	JR	Z,$?TXCOL
	LD	B,A
$?TXROW	LD	DE,40
	ADD	HL,DE
	DJNZ	$?TXROW
$?TXCOL	LD	A,E
	LD	E,A
	LD	D,0
	ADD	HL,DE
	POP	AF
	PUSH	AF
	LD	(HL),A

	; Render to bitmap
	; For each scanline s=0..7:
	;   screen_addr = $C000 + s*$0800 + row*80 + col*2
	;   font byte = FONT[(char-32)*8 + s]
	;   left nibble -> FONT_EXP[nib] = left byte
	;   right nibble -> FONT_EXP[nib] = right byte
	POP	AF
	PUSH	AF

	; Get font index
	SUB	32
	JR	NC,$?FIDX
	XOR	A
$?FIDX	CP	96
	JR	C,$?FOK
	LD	A,95
$?FOK
	; A = 0..95, font glyph = FONT_DATA + A*8
	ADD	A,A
	ADD	A,A
	ADD	A,A
	LD	E,A
	LD	D,0
	LD	HL,FONT_DATA
	ADD	HL,DE		;HL = font glyph address
	LD	IX,0
	PUSH	HL
	POP	IX		;IX = font pointer

	POP	AF		;A=char (discard)
	POP	DE		;D=row, E=col
	PUSH	DE

	; Scanline loop (s = 0..7)
	LD	BC,8*256+0	;B=8 scanlines, C=0
$?SCANLP	PUSH	BC
	; Get font byte for scanline C (= 8-B)
	LD	A,8
	SUB	B		;A = scanline 0-7
	LD	L,A
	LD	H,0
	ADD	HL,HL
	ADD	HL,HL
	ADD	HL,HL		;*8 (2048 = $0800)
	ADD	HL,HL
	PUSH	HL		;Save scanline*$0800

	; Font byte
	LD	A,C		;C = scanline (0-7)
	LD	E,A
	LD	D,0
	PUSH	IX
	POP	HL
	ADD	HL,DE
	LD	A,(HL)		;A = font byte for this scanline
	LD	B,A		;B = font byte

	; Check inverse
	LD	A,(INVIDEO)
	AND	80H
	JR	Z,$?NOINV
	LD	A,B
	XOR	0FFH
	LD	B,A
$?NOINV

	; Expand nibbles using table
	; Left nibble (bits 7-4)
	LD	A,B
	RRCA
	RRCA
	RRCA
	RRCA
	AND	0FH
	LD	E,A
	LD	D,0
	LD	HL,FONT_EXP
	ADD	HL,DE
	LD	C,(HL)		;C = left byte

	; Right nibble (bits 3-0)
	LD	A,B
	AND	0FH
	LD	E,A
	LD	HL,FONT_EXP
	ADD	HL,DE
	LD	B,(HL)		;B = right byte

	; Compute screen address = $C000 + scanline*$0800 + row*80 + col*2
	POP	HL		;HL = scanline*$0800
	LD	DE,SCR_BASE
	ADD	HL,DE		;HL = $C000 + scanline*$0800

	; Add row*80
	POP	DE		;D=row, E=col
	PUSH	DE
	LD	A,D		;row
	OR	A
	JR	Z,$?SKIPROW
	PUSH	BC
	LD	B,A
	LD	DE,80
$?ADDROW	ADD	HL,DE
	DJNZ	$?ADDROW
	POP	BC
$?SKIPROW
	; Add col*2
	LD	A,E
	ADD	A,A
	LD	E,A
	LD	D,0
	ADD	HL,DE		;HL = screen address

	; Write both bytes to screen
	LD	A,C
	LD	(HL),A
	INC	HL
	LD	A,B
	LD	(HL),A

	POP	DE		;D=row, E=col
	POP	BC		;B=scanline counter, C=scanline
	INC	C		;Next scanline
	DJNZ	$?SCANLP

	POP	DE
	POP	HL
	POP	BC
	RET

;==============================================================================
; Clear entire text buffer and screen
;==============================================================================
@CLS	PUSH	HL
	PUSH	DE
	PUSH	BC
	PUSH	AF

	; Clear text buffer with spaces
	LD	HL,TEXTBUF
	LD	DE,TEXTBUF+1
	LD	BC,999
	LD	A,' '
	LD	(HL),A
	LDIR

	; Clear bitmap screen ($C000-$C000+16000)
	LD	HL,SCR_BASE
	LD	DE,SCR_BASE+1
	LD	BC,SCR_SIZE-1
	XOR	A
	LD	(HL),A
	LDIR

	POP	AF
	POP	BC
	POP	DE
	POP	HL
	RET

;==============================================================================
; Main driver entry
;==============================================================================
DOBGN	LD	IX,DODATA
	JP	C,$?0_GET
	PUSH	BC
	LD	A,C
	BIT	4,(IX+DO_MASK)
	JR	NZ,$?1A
	OR	A
	JP	Z,TGGLCTL
	CP	20H
	JP	C,DO_CONTROL
$?1A	CP	0C0H
	JR	C,DONORM
	BIT	3,(IX+DO_MASK)
	JR	Z,DO_TABS

DONORM	LD	A,C
	LD	HL,(CURSOR)
	CALL	DO_PUT_CHAR
	RES	4,(IX+DO_MASK)
	LD	HL,(CURSOR)
	INC	L
	LD	A,L
	CP	CPC_COLS
	JR	C,$?ADV
	LD	L,0
	INC	H
	LD	A,H
	CP	CPC_ROWS
	JR	C,$?ADV
	DEC	H
	CALL	DO_SCROLL
$?ADV	LD	(CURSOR),HL
	POP	BC
	CP	A
	RET

DO_TABS	SUB	0C0H
	JR	Z,$?TR
	LD	B,A
$?TL	LD	C,' '
	PUSH	BC
	CALL	DONORM
	POP	BC
	DJNZ	$?TL
$?TR	POP	BC
	CP	A
	RET

;==============================================================================
; Control characters
;==============================================================================
DO_CONTROL
	LD	HL,$?CRET
	PUSH	HL
	CP	08H
	JR	Z,BACKSPA
	CP	0AH
	JR	Z,LINFEED
	SUB	0DH
	JP	Z,LINFEED
	DEC	A
	JR	Z,CRSON
	DEC	A
	JR	Z,CRSOFF
	DEC	A
	JR	Z,DO_INVERT_ENA
	DEC	A
	JR	Z,DO_INVERT_OFF
	SUB	4
	JR	Z,TGGLTAB
	DEC	A
	JR	Z,TGGLALT
	DEC	A
	JR	Z,SET40
	DEC	A
	JR	Z,CRSBKSP
	DEC	A
	JR	Z,CRSFRWD
	DEC	A
	JR	Z,CRSDOWN
	DEC	A
	JR	Z,CRSUP
	DEC	A
	JP	Z,CRSHOME
	DEC	A
	JP	Z,CRSBOL
	DEC	A
	JP	Z,CLREOL
	DEC	A
	JP	Z,CLREOF
$?CRET	XOR	A
	RET

BACKSPA	CALL	CRSBKSP
	RET	Z
	LD	C,' '
	CALL	DONORM
	RET

CRSBKSP	LD	HL,(CURSOR)
	LD	A,L
	OR	A
	RET	Z
	DEC	L
	LD	(CURSOR),HL
	RET
CRSFRWD	LD	HL,(CURSOR)
	LD	A,L
	CP	CPC_COLS-1
	RET	NC
	INC	L
	LD	(CURSOR),HL
	RET
CRSUP	LD	HL,(CURSOR)
	LD	A,H
	OR	A
	RET	Z
	DEC	H
	LD	(CURSOR),HL
	RET
CRSDOWN	LD	HL,(CURSOR)
	LD	A,H
	CP	CPC_ROWS-1
	JR	Z,DO_SCROLL
	INC	H
	LD	(CURSOR),HL
	RET
CRSBOL	LD	HL,(CURSOR)
	LD	L,0
	LD	(CURSOR),HL
	RET
CRSHOME	LD	HL,0
	LD	(CURSOR),HL
	XOR	A
	LD	(INVIDEO),A
	RET
CRSON	RET
CRSOFF	RET
DO_INVERT_ENA	LD	A,80H
	LD	(INVIDEO),A
	RET
DO_INVERT_OFF	XOR	A
	LD	(INVIDEO),A
	RET

LINFEED	CALL	CRSBOL
	LD	HL,(CURSOR)
	LD	A,H
	CP	CPC_ROWS-1
	JR	Z,DO_SCROLL
	INC	H
	LD	(CURSOR),HL
	RET

DO_SCROLL
	PUSH	HL
	PUSH	DE
	PUSH	BC
	; Move text lines 1..24 -> 0..23
	LD	HL,TEXTBUF+40
	LD	DE,TEXTBUF
	LD	BC,40*24
	LDIR
	; Clear last line
	LD	HL,TEXTBUF+40*24
	LD	B,40
	LD	A,' '
$?SCRLP	LD	(HL),A
	INC	HL
	DJNZ	$?SCRLP

	; Scroll bitmap: move bytes from row 1+ to row 0+
	LD	BC,SCR_BASE
	LD	HL,SCR_BASE+SCR_ROW_BYTES
	LD	DE,SCR_BASE
	LD	BC,SCR_ROW_BYTES*24
	LDIR
	; Clear last bitmap row
	LD	HL,SCR_BASE+SCR_ROW_BYTES*24
	LD	B,40
	LD	A,0
$?SCBMLP	LD	(HL),A
	INC	HL
	LD	(HL),A
	INC	HL
	DJNZ	$?SCBMLP

	POP	BC
	POP	DE
	POP	HL
	RET

CLREOL	PUSH	HL
	PUSH	BC
	LD	HL,(CURSOR)
	LD	A,CPC_COLS
	SUB	L
	LD	B,A
	INC	B
	DEC	B
	JR	Z,$?CEOK
	LD	A,' '
$?CELP	PUSH	BC
	PUSH	HL
	PUSH	AF
	CALL	DO_PUT_CHAR
	POP	AF
	POP	HL
	POP	BC
	INC	L
	DJNZ	$?CELP
$?CEOK	POP	BC
	POP	HL
	RET

CLREOF	PUSH	HL
	PUSH	BC
	LD	HL,(CURSOR)
$?CFLP	LD	A,H
	CP	CPC_ROWS
	JR	NC,$?CFDN
	PUSH	HL
	LD	A,(CURSOR+1)
	LD	L,A
	LD	A,CPC_COLS
	SUB	L
	LD	B,A
	INC	B
	DEC	B
	JR	Z,$?CFNX
	LD	A,' '
$?CFCL	PUSH	BC
	PUSH	HL
	PUSH	AF
	CALL	DO_PUT_CHAR
	POP	AF
	POP	HL
	POP	BC
	INC	L
	DJNZ	$?CFCL
$?CFNX	POP	HL
	INC	H
	LD	L,0
	JR	$?CFLP
$?CFDN	POP	BC
	POP	HL
	RET

TGGLCTL	LD	A,10H
	XOR	(IX+DO_MASK)
	LD	(IX+DO_MASK),A
	RET
TGGLTAB	LD	A,8
	XOR	(IX+DO_MASK)
	LD	(IX+DO_MASK),A
	RET
TGGLALT	RET
SET40	RET

;==============================================================================
; GET at cursor position
;==============================================================================
$?0_GET	PUSH	HL
	LD	HL,(CURSOR)
	LD	A,H
	LD	HL,TEXTBUF
	OR	A
	JR	Z,$?GTOFF
	LD	B,A
$?GTROW	LD	DE,40
	ADD	HL,DE
	DJNZ	$?GTROW
$?GTOFF	POP	DE
	LD	A,E
	LD	E,A
	LD	D,0
	ADD	HL,DE
	LD	A,(HL)
	LD	C,A
	POP	HL
	CP	A
	RET

;==============================================================================
; @VDCTL handler
;==============================================================================
@_VDCTL
	LD	A,9
	CP	B
	JR	Z,VIDLIN
	LD	A,43
	DEC	B
	JR	Z,$?GRC
	DEC	B
	JR	Z,$?PRC
	DEC	B
	JR	Z,$?VT3
	DEC	B
	JR	Z,$?A2R
	DEC	B
	JR	Z,$?VM1
	DEC	B
	JR	Z,$?VME
	DEC	B
	JP	Z,$?SSC
	DEC	B
	RET	NZ
	PUSH	HL
	LD	HL,CRSCHAR
	LD	A,(HL)
	LD	(HL),C
	POP	HL
	RET

$?VT3	LD	(CURSOR),HL
	RET
$?PRC	PUSH	HL
	PUSH	BC
	LD	A,C
	CALL	DO_PUT_CHAR
	POP	BC
	POP	HL
	RET
$?GRC	PUSH	HL
	LD	A,H
	LD	HL,TEXTBUF
	OR	A
	JR	Z,$?GRO
	LD	B,A
$?GRM	LD	DE,40
	ADD	HL,DE
	DJNZ	$?GRM
$?GRO	POP	DE
	PUSH	DE
	LD	A,E
	LD	E,A
	LD	D,0
	ADD	HL,DE
	LD	A,(HL)
	LD	C,A
	POP	HL
	CP	A
	RET
$?A2R	LD	HL,(CURSOR)
	RET
$?VM1	EX	DE,HL
$?VME	LD	DE,TEXTBUF
	LD	BC,CPC_CRTSIZE
	LDIR
	CP	A
	RET
$?SSC	LD	A,C
	AND	7
	LD	C,A
	LD	A,(DODATA)
	AND	0F8H
	OR	C
	LD	(DODATA),A
	XOR	A
	RET

VIDLIN	XOR	A
	RET

DOEND	EQU	$-1

